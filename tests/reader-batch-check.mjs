import assert from "node:assert/strict";
import {randomUUID,createHash} from "node:crypto";
import {memoryStorage,schema,storageCache} from "./entity-fixture.mjs";
const fixture=memoryStorage(),calls=[],send=fixture.storage.client.send.bind(fixture.storage.client);
fixture.storage.client.send=async command=>{calls.push({name:command.constructor.name,key:command.input.Key || command.input.Prefix});return send(command);};
const section={id:"s",name:"Section",description:"",icon:"folder"};
const library={version:1,sections:[section],projects:Array.from({length:50},(_,n)=>({id:`idea-${n}`,name:`Idea ${n}`,sectionId:"s",description:"",cover:"forest",updatedAt:"2026-01-01T00:00:00Z",blocks:[{id:"a",heading:"A",text:`Body ${n}`},{id:"b",heading:"B",text:`Unchanged ${n}`}]}))};
try {
  const values=schema.flattenLibrary(library);
  await fixture.entities().save({operationId:randomUUID(),heads:[],changes:Object.entries(values).map(([key,value])=>({key,value,base:[]}))});
  calls.length=0;
  const initial=await fixture.entities().readReaderBatch({pages:[{}],sidebar:true,bodies:["idea-0"]});
  assert.equal(initial.pages.length,2);assert.equal(initial.pages[0].page.ideas.length,24);assert.equal(initial.pages[1].page.ideas.length,4);
  assert.equal(initial.bodies.length,1);assert.equal(initial.bodies[0].read.target.id,"idea-0");
  assert.equal(calls.filter(call=>call.name==="ListObjectsV2Command" && call.key.endsWith("/indexes/")).length,1,"One packet shares one history/index snapshot");
  const baseline=await fixture.entities().catalogIndex(),key=schema.entityKey("block","idea-0","a");
  await fixture.entities().save({operationId:randomUUID(),heads:baseline.heads,changes:[{key,base:baseline.index[key],value:{...values[key],text:"Changed text"}}]});
  storageCache.clearStorageReadCache();calls.length=0;
  const delta=await fixture.entities().readReaderBatch({since:initial.heads,watch:["idea-0"]});
  assert.equal(delta.pages.length,0);assert.equal(delta.bodies.length,0);
  assert.equal(delta.changes.records.find(record=>record.key===key).value.text,"Changed text");
  assert.ok(!JSON.stringify(delta).includes("Unchanged 0"),"An unchanged block is not downloaded again");
  assert.ok(!JSON.stringify(delta).includes("Body 49"),"Closed bodies never enter the packet");
  assert.ok(!calls.some(call=>call.key.includes("/catalog-v1/") || call.name==="PutObjectCommand"),"A delta neither rebuilds nor reads the whole catalog");
  const changedGets=calls.filter(call=>call.name==="GetObjectCommand").length;
  assert.ok(changedGets<=6,`One changed block requires at most six cold Class B GETs, got ${changedGets}`);
  storageCache.clearStorageReadCache();calls.length=0;
  const unchanged=await fixture.entities().readReaderBatch({since:delta.heads,watch:["idea-0"]});
  assert.deepEqual(unchanged.changes.records,[]);assert.equal(unchanged.pages.length,0);assert.equal(unchanged.bodies.length,0);
  const controlGets=calls.filter(call=>call.name==="GetObjectCommand").length;
  assert.equal(controlGets,1,"The unchanged ten-minute check reads only its current manifest");
  const absent=randomUUID();
  const observed=await fixture.entities().readReaderBatch({since:delta.heads,observe:[...initial.heads,...delta.heads,absent]});
  assert.deepEqual(observed.observed,[...initial.heads,...delta.heads]);
  await assert.rejects(()=>fixture.entities().readReaderBatch({observe:["invalid"]}),error=>error.status===400);
  const closed=await fixture.entities().readReaderBatch({since:initial.heads});
  assert.ok(!closed.changes.records.some(record=>schema.keyParts(record.key).kind==="block"),"Without cached bodies a change packet contains metadata only");
  await assert.rejects(()=>fixture.entities().readReaderBatch({watch:Array.from({length:65},(_,n)=>String(n))}),error=>error.status===400);
  const mediaFiles=["image-one","image-two"].map(text=>{
    const body=Buffer.from(text),sha256=createHash("sha256").update(body).digest("hex"),md5=createHash("md5").update(body).digest("hex");
    const file={id:`${sha256}-${md5}`,sha256,md5,size:body.length,mime:"image/png"};
    fixture.objects.set(`${fixture.storage.prefix}/media/${file.id}`,{body,type:file.mime,metadata:{sha256},md5});return file;
  });
  const beforeMedia=await fixture.entities().catalogIndex();
  await fixture.entities().save({operationId:randomUUID(),heads:beforeMedia.heads,changes:mediaFiles.map(file=>({key:schema.entityKey("media",file.id),value:file,base:[]}))});
  storageCache.clearStorageReadCache();calls.length=0;
  const signed=await fixture.entities().readReaderBatch({mediaOnly:true,media:mediaFiles.map(file=>file.id)});
  assert.equal(signed.media.length,2);assert.ok(signed.media.every(value=>value.download?.expiresIn===300));
  assert.equal(signed.pages.length,0);assert.equal(signed.changes.records.length,0);
  assert.ok(!calls.some(call=>call.name==="PutObjectCommand"),"Media-only packets never rebuild a catalog or advance a document checkpoint");
  assert.equal(calls.filter(call=>call.name==="ListObjectsV2Command" && call.key.endsWith("/indexes/")).length,1);
  console.log(`Reader batch budget (50 ideas, cold cache): changed block ${changedGets} Class B GETs; unchanged control ${controlGets}; no catalog rebuild or unrelated block downloads.`);
}finally{fixture.storage.client.destroy();}
